// ── Helper functions ──────────────────────────────────────────────────────────

/** Keep the first product for each distinct 3D model. */
export const getDistinctProducts = (products) => {
  const seenModels = new Set();
  return products.filter((product) => {
    if (!product.modelUrl) return true;

    let modelKey;
    try {
      modelKey = new URL(product.modelUrl, 'https://catalogue.invalid').pathname.toLowerCase();
    } catch {
      modelKey = product.modelUrl.split(/[?#]/, 1)[0].toLowerCase();
    }

    if (seenModels.has(modelKey)) return false;
    seenModels.add(modelKey);
    return true;
  });
};

/** Filter + search products from mock data */
export const filterProducts = ({ category = 'All', search = '' } = {}) => {
  let result = [...mockProducts];
  if (category && category !== 'All') {
    result = result.filter((p) => p.category === category);
  }
  if (search.trim()) {
    const q = search.trim().toLowerCase();
    result = result.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        (p.description && p.description.toLowerCase().includes(q)) ||
        (p.material && p.material.toLowerCase().includes(q))
    );
  }
  return getDistinctProducts(result);
};

/** Get a single product by id or _id */
export const getProductById = (id) =>
  mockProducts.find((p) => p.id === id || p._id === id) || null;

/** Get featured products (first N) */
export const getFeatured = (n = 6) => getDistinctProducts(mockProducts).slice(0, n);
